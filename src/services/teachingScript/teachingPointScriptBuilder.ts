export function get1MD1TeachingScriptSummary(): PackageTeachingScript {
  const points = build1MD1TeachingPoints();
  const totalDurationSeconds = points.reduce((sum, p) => sum + p.durationSeconds, 0);

  const pointsByBlock: Record<string, TeachingPoint[]> = {};
  const pointsBySlide: Record<number, TeachingPoint[]> = {};

  points.forEach(p => {
    if (!pointsByBlock[p.teachingBlockId]) pointsByBlock[p.teachingBlockId] = [];
    pointsByBlock[p.teachingBlockId].push(p);

    if (!pointsBySlide[p.slideNumber]) pointsBySlide[p.slideNumber] = [];
    pointsBySlide[p.slideNumber].push(p);
  });

  return {
    packageId: 'LPKG-1MD1-001',
    totalPoints: points.length,
    totalDurationSeconds,
    totalDurationMinutes: totalDurationSeconds / 60,
    teachingBlocksCount: Object.keys(pointsByBlock).length,
    slidesCount: Object.keys(pointsBySlide).length,
    pointsByBlock,
    pointsBySlide
  };
}
